void TileManager::Render(float cameraX) {
	for (int y = 0; y < map.size(); y++)
	{
		for (int x = 0; x < map[y].size(); x++)
		{
			int type = map[y][x].type;

			int drawX = (static_cast<int>(map[y][x].position.x) - static_cast<int>(cameraX));
			int drawY = static_cast<int>(map[y][x].position.y);
			switch (type)
			{
			case TILE_EMPTY:
				break;

			case TILE_GROUND:
				DrawBox(drawX, drawY, drawX + TILE_SIZE, drawY + TILE_SIZE, GetColor(255, 0, 0), true);
				break;
			case TILE_BLOCK:
				DrawBox(drawX, drawY, drawX + TILE_SIZE, drawY + TILE_SIZE, GetColor(128, 64, 64), true);
				break;
			case TILE_QUESTION:
				DrawBox(drawX, drawY, drawX + TILE_SIZE, drawY + TILE_SIZE, GetColor(255, 255, 0), true);
				break;
			case TILE_PIPE_LEFT_TOP:
				DrawBox(drawX, drawY, drawX + TILE_SIZE, drawY + TILE_SIZE, GetColor(0, 200, 0), true);
				break;
			case TILE_PIPE_RIGHT_TOP:
				DrawBox(drawX, drawY, drawX + TILE_SIZE, drawY + TILE_SIZE, GetColor(0, 220, 0), true);
				break;
			case TILE_PIPE_LEFT_BOTTOM:
				DrawBox(drawX, drawY, drawX + TILE_SIZE, drawY + TILE_SIZE, GetColor(0, 180, 0), true);
				break;
			case TILE_PIPE_RIGHT_BOTTOM:
				DrawBox(drawX, drawY, drawX + TILE_SIZE, drawY + TILE_SIZE, GetColor(0, 180, 0), true);
				break;
			case TILE_HIDE_BLOCK:
				DrawBox(drawX, drawY, drawX + TILE_SIZE, drawY + TILE_SIZE, GetColor(64, 64, 128), false);
				break;
			case TILE_HITTED_BLOCK:
				DrawBox(drawX, drawY, drawX + TILE_SIZE, drawY + TILE_SIZE, GetColor(64, 64, 128), true);
			}
		}
	}
}

bool TileManager::IsSolid(int x, int y)
{
	if (y < 0 || y >= map.size())
		return false;

	if (x < 0 || x >= map[y].size())
		return false;

	return map[y][x].type != TILE_EMPTY;
}

void TileManager::HitTile(int x, int y, bool breakable)
{
	if (map[y][x].breakable && breakable)
	{
		map[y][x].type = TILE_EMPTY;
		//エフェクトを出す
	}
	if (map[y][x].type == TILE_BLOCK || map[y][x].type == TILE_QUESTION)
	{
		map[y][x].speedY = -HIT_TILE_SPEED;
	}
	if (map[y][x].type == TILE_QUESTION || map[y][x].type == TILE_HIDE_BLOCK)
	{
#if 1
		map[y][x].itemType = ITEM_FIREFLOWER;
#endif
		map[y][x].type = TILE_HITTED_BLOCK;
		switch (ItemType(map[y][x].itemType))
		{
		case ITEM_COIN:
			//コインを出す
			break;
		case ITEM_SUPERMASHROOM:
			AddMash(map[y][x].basePosition, map[y][x].itemType);
			break;
		case ITEM_1UPMASHROOM:
			//アイテムを出す
			AddMash(map[y][x].basePosition, map[y][x].itemType);
			break;
		case ITEM_FIREFLOWER:
			AddFireFlower(map[y][x].basePosition, map[y][x].itemType);
			break;
		case ITEM_STAR:
			AddStar(map[y][x].basePosition, map[y][x].itemType);
			break;
		}
	}
}
